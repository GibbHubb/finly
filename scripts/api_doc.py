"""F47 — keep docs/technical/api.md's endpoint table in step with the live OpenAPI schema.

    python scripts/api_doc.py --write   # regenerate the table between the markers
    python scripts/api_doc.py --check   # CI: fail if any route in openapi.json is not in the table

The schema comes from `app.openapi()` (no server needed). Run from the repo root with the
backend's dependencies installed. `--check` compares (method, path) pairs only, so hand-edited
Purpose text survives; it fails naming every route the table is missing.
"""
from __future__ import annotations

import argparse
import re
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "technical" / "api.md"
BEGIN = "<!-- api-table:begin (generated by scripts/api_doc.py --write) -->"
END = "<!-- api-table:end -->"

# Routes guarded by something other than the bearer JWT OpenAPI can see.
AUTH_OVERRIDES = {
    "/api/v1/tasks/bank-sync": "cron secret",
    "/api/v1/tasks/demo-reset": "cron secret",
    "/api/v1/auth/refresh": "refresh token (body)",
    "/api/v1/auth/logout": "refresh token (body)",
}

ROW = re.compile(r"^\|\s*`?(GET|POST|PUT|PATCH|DELETE)`?\s*\|\s*`([^`]+)`\s*\|", re.M)


def _purpose(description: str) -> str:
    """First sentence of the docstring's first paragraph, without a leading ticket tag."""
    para = " ".join(description.strip().split("\n\n")[0].split())
    para = re.sub(r"^F[\w-]+\s+\W\s+", "", para)
    sentence = re.split(r"(?<=[.:])\s", para, maxsplit=1)[0].rstrip(":")
    return sentence[:1].upper() + sentence[1:]


def _operations() -> list[tuple[str, str, str, str]]:
    sys.path.insert(0, str(ROOT / "backend"))
    warnings.simplefilter("ignore")  # FastAPI warns about the GET+POST cron routes' shared op id
    from app.main import app

    rows = []
    for path, item in app.openapi()["paths"].items():
        for method, op in item.items():
            auth = AUTH_OVERRIDES.get(path) or ("bearer JWT" if op.get("security") else "none")
            purpose = _purpose(op.get("description") or "") or op.get("summary", "")
            rows.append((method.upper(), path, auth, purpose.replace("|", "\\|")))
    return rows


def _table(rows) -> str:
    lines = ["| Method | Path | Auth | Purpose |", "|--------|------|------|---------|"]
    lines += [f"| `{m}` | `{p}` | {a} | {u} |" for m, p, a, u in sorted(rows, key=lambda r: (r[1], r[0]))]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = _operations()
    text = DOC.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"{DOC}: markers missing; expected {BEGIN!r} ... {END!r}")
        return 1

    if args.write:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        DOC.write_text(f"{head}{BEGIN}\n{_table(rows)}\n{END}{tail}", encoding="utf-8", newline="\n")
        print(f"wrote {len(rows)} routes to {DOC.relative_to(ROOT)}")
        return 0

    documented = {(m, p) for m, p in ROW.findall(text.split(BEGIN, 1)[1].split(END, 1)[0])}
    missing = sorted({(m, p) for m, p, _, _ in rows} - documented, key=lambda r: (r[1], r[0]))
    if missing:
        print(f"{DOC.relative_to(ROOT)} is missing {len(missing)} route(s) the API serves:")
        for m, p in missing:
            print(f"  {m} {p}")
        print("Run: python scripts/api_doc.py --write")
        return 1
    print(f"api.md documents all {len(rows)} routes in openapi.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
